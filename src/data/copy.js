function c(locale, key, fallback) {
  const table = COPY[locale];
  if (table && table[key] !== undefined) return table[key];
  return fallback !== undefined ? fallback : key;
}

/* True when a locale has a translation for the key, so pages can flag
   English-only long-form content honestly. */
function hasCopy(locale, key) {
  return !!(COPY[locale] && COPY[locale][key] !== undefined);
}

